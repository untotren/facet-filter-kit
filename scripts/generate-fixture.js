// Generates fixtures/items.js: 250 deterministic sample items across six
// fictional categories. Run with `npm run fixture`; the output is committed
// and test/fixture.test.js checks it still matches this generator.

import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SEED = 220;
export const ITEM_COUNT = 250;

export const CATEGORIES = ['Aetherworks', 'Brinecraft', 'Cindermoor', 'Duskweave', 'Emberline', 'Frostmere'];
export const REGIONS = ['North Reach', 'Saltmarsh', 'Eastern Spires', 'Westvale', 'The Isles'];
export const TAGS = [
  'handmade', 'limited', 'vintage', 'eco', 'bundle', 'new',
  'bestseller', 'refurbished', 'gift', 'compact', 'modular', 'heirloom',
];

const NOUNS = {
  Aetherworks: ['Skylens', 'Drift Compass', 'Cloud Anchor', 'Wind Loom', 'Glider Kit'],
  Brinecraft: ['Tide Jar', 'Kelp Rope', 'Salt Lantern', 'Pearl Hook', 'Reef Net'],
  Cindermoor: ['Ash Kettle', 'Coal Bellows', 'Ember Tongs', 'Smoke Pipe', 'Slag Bowl'],
  Duskweave: ['Shade Cloak', 'Night Banner', 'Gloam Scarf', 'Twilight Rug', 'Moth Veil'],
  Emberline: ['Spark Lamp', 'Flint Box', 'Glow Wick', 'Heat Stone', 'Torch Rod'],
  Frostmere: ['Rime Flask', 'Ice Skates', 'Snow Lattice', 'Chill Box', 'Hoar Bell'],
};
const ADJECTIVES = ['Quiet', 'Bold', 'Gilded', 'Weathered', 'Nimble', 'Lucent', 'Hollow', 'Patient'];

// mulberry32: small, fast, seedable 32-bit PRNG.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function generateItems(seed = SEED, count = ITEM_COUNT) {
  const random = mulberry32(seed);
  const int = (lo, hi) => lo + Math.floor(random() * (hi - lo + 1));
  const pick = (list) => list[int(0, list.length - 1)];

  const items = [];
  for (let i = 0; i < count; i++) {
    const category = CATEGORIES[i % CATEGORIES.length];
    const tagCount = int(1, 4);
    const tags = [];
    while (tags.length < tagCount) {
      const tag = pick(TAGS);
      if (!tags.includes(tag)) tags.push(tag);
    }
    items.push({
      id: `item-${String(i + 1).padStart(3, '0')}`,
      title: `${pick(ADJECTIVES)} ${pick(NOUNS[category])}`,
      tags,
      fields: {
        category,
        region: pick(REGIONS),
        price: int(500, 50000) / 100,
        rating: int(10, 50) / 10,
        year: int(1990, 2025),
      },
    });
  }
  return items;
}

export function renderModule(items) {
  return (
    '// Generated by scripts/generate-fixture.js. Do not edit by hand; run `npm run fixture`.\n' +
    `const items = ${JSON.stringify(items, null, 2)};\n\nexport default items;\n`
  );
}

export const OUTPUT_PATH = fileURLToPath(new URL('../fixtures/items.js', import.meta.url));

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT_PATH, renderModule(generateItems()));
  console.log(`Wrote ${ITEM_COUNT} items to ${OUTPUT_PATH}`);
}
